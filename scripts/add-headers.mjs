/**
 * Applies the confidential ownership banner to every source file.
 *
 * This is the only place where the banner is assembled (see scripts/header.mjs);
 * files themselves stay clean. The script is idempotent: it strips an existing
 * banner and re-adds it, so re-running is always safe.
 *
 * Usage:
 *   pnpm headers          # apply / refresh banners
 *   pnpm headers:check    # CI gate — fails if any file is missing its banner
 *
 * Strict JSON files cannot hold comments, so they carry a single top-level "//"
 * key instead. JSON with comments (tsconfig) uses `//` line comments.
 */

