function styleFor(file) {
  const base = file.split(sep).pop() ?? file;
  const ext = extname(base).toLowerCase();

  // tsconfig files are JSONC in practice (comments allowed); apply the banner
  // as // comments so the full ownership notice survives, not just a "//" key.
  if (base.startsWith("tsconfig") && ext === ".json") return "slash";
  if (base.endsWith(".jsonc")) return "slash";
  if (ext === ".json") return "json";
  if (ext === ".md" || ext === ".mdx") return "html";
  if (
    [".toml", ".yaml", ".yml", ".ini", ".conf", ".example"].includes(ext) ||
    base.startsWith(".env") ||
    base === ".gitignore" ||
    base === ".gitattributes" ||
    base === ".editorconfig" ||
    base === "Dockerfile"
  ) {
    return "hash";
  }
  if ([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".css", ".sql"].includes(ext)) {
    return "block";
  }
  return null;
}

function walk(dir, files = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(join(dir, entry.name), files);
    } else if (entry.isFile()) {
      files.push(join(dir, entry.name));
    }
  }
  return files;
}

function summaryFor(rel) {
  return SUMMARIES[rel] ?? "Part of the EduRelay platform.";
}

/** Apply a comment banner (block/html/hash/slash) to a text file. */
function applyCommentBanner(text, rel, style) {
  const { prologue, rest } = splitPrologue(text);
  const clean = stripHeader(rest, style);
  const header = renderHeader({ file: rel, summary: summaryFor(rel), style });
  return `${prologue}${header}${clean}`;
}

/**
 * Apply the single-line "//" banner to strict JSON (no comment support).
 *
 * Only the banner VALUE is replaced: rewriting the whole document with
 * JSON.stringify would fight Biome's formatter (it expands arrays), so every
 * push would produce a spurious diff. Keeping the rest of the text untouched
 * lets the formatter and the header script coexist.
 */
function applyJsonBanner(text) {
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    return null; // not strict JSON — leave untouched, report it
  }
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) return null;

  const banner = JSON.stringify(jsonBanner());

  if (Object.hasOwn(parsed, "//")) {
    return text.replace(/("\/\/"\s*:\s*)"(?:[^"\\]|\\.)*"/, `$1${banner}`);
  }

  return text.replace(/^(\s*\{)/, `$1\n  "//": ${banner},`);
}

let changed = 0;
let skippedJson = 0;
const failures = [];

for (const absolute of walk(ROOT)) {
  const rel = relative(ROOT, absolute).split(sep).join("/");
  const base = absolute.split(sep).pop() ?? "";

  if (SKIP_FILES.has(base) || SKIP_EXTENSIONS.has(extname(base).toLowerCase())) continue;
  if (rel.startsWith("supabase/.temp/")) continue;

  const style = styleFor(absolute);
  if (!style) continue;

  const original = readFileSync(absolute, "utf8").replace(/\r\n/g, "\n");

  let next;
  if (style === "json") {
    next = applyJsonBanner(original);
    if (next === null) {
      skippedJson += 1;
      continue;
    }
  } else {
    next = applyCommentBanner(original, rel, style);
  }

  if (next === original) continue;

  if (CHECK) {
    failures.push(rel);
    continue;
  }

  writeFileSync(absolute, next, "utf8");
  changed += 1;
}

if (CHECK) {
  if (failures.length > 0) {
    console.error(`header check: ${failures.length} file(s) missing or out of date:`);
    for (const file of failures) console.error(`  - ${file}`);
    console.error("Run `pnpm headers` to fix.");
    process.exit(1);
  }
  console.log("header check: all files carry the ownership banner.");
} else {
  console.log(
    `headers: updated ${changed} file(s)${skippedJson ? `, skipped ${skippedJson}` : ""}.`,
  );
}
